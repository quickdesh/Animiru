        bookmarkCount: Double,
        // AY -->
        fillermarkCount: Double,
        // <-- AY
        categories: String,
    ): LibraryAnime = LibraryAnime(
        anime = mapAnime(
            id,
            source,
            url,
            artist,
            author,
            description,
            genre,
            title,
            status,
            thumbnailUrl,
            favorite,
            lastUpdate,
            nextUpdate,
            initialized,
            viewerFlags,
            episodeFlags,
            coverLastModified,
            dateAdded,
            updateStrategy,
            calculateInterval,
            lastModifiedAt,
            favoriteModifiedAt,
            version,
            isSyncing,
            notes,
            // AY -->
            fetchType,
            parentId,
            seasonFlags,
            seasonNumber,
            seasonSourceOrder,
            backgroundUrl,
            backgroundLastModified,
            // <-- AY
        ),
        categories = categories.split(",").map { it.toLong() },
        totalCount = totalCount,
        seenCount = seenCount.toLong(),
        bookmarkCount = bookmarkCount.toLong(),
        // AY -->
        fillermarkCount = fillermarkCount.toLong(),
        // <-- AY
        latestUpload = latestUpload,
        episodeFetchedAt = episodeFetchedAt,
        lastSeen = lastSeen,
    )

